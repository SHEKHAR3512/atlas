from typing import Any, Dict
from services.atlas.ai.base import AIProvider


class DisabledAIProvider(AIProvider):
    """
    Deterministic rule-based fallback provider.
    Ensures research summaries and explanations are generated deterministically
    when local AI / Ollama is not active.
    """

    async def generate(self, prompt: str) -> str:
        return "[Deterministic AI Disabled] Quantitative research running in autonomous deterministic mode."

    async def structured_generate(self, prompt: str, schema: Dict[str, Any]) -> Dict[str, Any]:
        return {
            "hypothesis": "Deterministic quantitative hypothesis generated by research lab engine.",
            "economic_reason": "Risk premia extraction based on empirical market structure.",
            "features": ["trend", "volatility", "momentum"],
            "entry_logic": "Quantitative indicator threshold trigger.",
            "exit_logic": "Trailing volatility stop or regime shift.",
            "risks": ["Slippage on high volatility", "Regime shift to bear market"],
            "required_validation": ["Walk-forward folds", "Monte Carlo ruin analysis"],
        }

    async def summarize(self, text: str) -> str:
        return f"Summary: Experiment executed with deterministic statistical validation. {text[:200]}..."
